export const getCommodity = (id: string) => COMMODITIES.find((c) => c.id === id);

/** Simulated "vision model" lookup: filename keyword match, else deterministic hash. */
export function detectCommodity(fileName: string): { commodity: Commodity; confidence: number } {
  const lower = fileName.toLowerCase();
  const keywords: Record<string, string> = {
    apple: "apple",
    tomato: "tomato",
    spinach: "spinach",
    leaf: "spinach",
    green: "spinach",
    banana: "banana",
    milk: "milk",
    bread: "bread",
    meat: "meat",
    chicken: "meat",
    rice: "rice",
    pulse: "pulses",
    soy: "pulses",
    dal: "pulses",
    spice: "spices",
    chili: "spices",
    chip: "chips",
    pea: "frozen-peas",
    oil: "oil",
    potato: "potato",
  };

  for (const [key, id] of Object.entries(keywords)) {
    if (lower.includes(key)) {
      const commodity = getCommodity(id)!;
      return { commodity, confidence: 92 + (key.length % 6) };
    }
  }

  let hash = 0;
  for (let i = 0; i < fileName.length; i++) hash = (hash * 31 + fileName.charCodeAt(i)) % 9973;
  const commodity = COMMODITIES[hash % COMMODITIES.length]!;
  return { commodity, confidence: 78 + (hash % 12) };
}
